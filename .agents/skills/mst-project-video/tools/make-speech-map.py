"""Writes src/<Topic>/speechMap.ts: for every narration file, the share of speech already spoken at each video frame (30fps).
Subtitles read it so a caption chunk changes when the voice reaches it, pauses included. Run again after regenerating the voice.
Usage: python .claude/skills/mst-project-video/tools/make-speech-map.py <TopicName>"""
import json, sys, wave
import numpy as np

topic = sys.argv[1]
manifest = json.load(open(f"public/audio/{topic}/manifest.json", encoding="utf-8"))
out = {}
for scene in manifest["scenes"]:
    w = wave.open("public/" + scene["audioPath"])
    sr, ch = w.getframerate(), w.getnchannels()
    a = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float)
    if ch > 1:
        a = a.reshape(-1, ch).mean(1)
    hop = sr // 30
    n = len(a) // hop
    rms = np.sqrt((a[: n * hop].reshape(n, hop) ** 2).mean(1))
    voiced = rms > 0.08 * np.percentile(rms, 95)
    # Gaps shorter than ~5 frames are breaths between words, not pauses: count them as speech.
    idx = np.where(voiced)[0]
    for i, j in zip(idx[:-1], idx[1:]):
        if 1 < j - i <= 5:
            voiced[i : j + 1] = True
    cum = np.cumsum(voiced) / voiced.sum()
    out[scene["audioPath"]] = [round(float(x), 3) for x in cum]

ts = "// Auto-generated by make-speech-map.py (mst-project-video/tools): share of speech already spoken at each frame of every narration file.\n"
ts += "export const speechMap: Record<string, number[]> = " + json.dumps(out) + ";\n"
open(f"src/{topic}/speechMap.ts", "w", encoding="utf-8").write(ts)
print("ok", len(out))
